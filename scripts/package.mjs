import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const manifest = JSON.parse(await readFile('manifest.json', 'utf8'));
const folder = `dist/${manifest.id}`;
await mkdir(folder, { recursive: true });
const files = ['main.js', 'manifest.json'];
for (const file of files) await cp(file, `${folder}/${file}`);
const checksums = [];
for (const file of files) checksums.push(`${createHash('sha256').update(await readFile(`${folder}/${file}`)).digest('hex')}  ${file}`);
await writeFile('dist/SHA256SUMS.txt', checksums.join('\n') + '\n');
const archive = `${manifest.id}-${manifest.version}.zip`;
execFileSync('zip', ['-q', '-r', archive, manifest.id], { cwd: 'dist' });
console.info(`Built dist/${archive}; direct release assets are in ${folder}/`);
